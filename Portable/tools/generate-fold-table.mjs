/** Everything outside ASCII escaped, so a soft hyphen or a joiner in the
 *  fixture is something a diff shows rather than something it hides. */
const beyondAscii = new RegExp(`[${String.fromCharCode(0x7f)}-${String.fromCharCode(0xffff)}]`, 'g')
const visible = (json) => json.replace(beyondAscii, (character) =>
  `\\u${character.charCodeAt(0).toString(16).padStart(4, '0')}`)

