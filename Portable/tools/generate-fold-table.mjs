/**
 * Writes `src/shared/foldTable.ts` and `src/test/fixtures/macSearch.json`
 * from Foundation itself.
 *
 * Portable's search has to fold text the way the Mac's does — one case, no
 * accents, one width, a hyphen at the end of a line joining rather than
 * separating — or the same library answers the same query differently on two
 * desktops. JavaScript has nothing like `String.folding(options:locale:)`, and
 * its nearest neighbours (NFKD, `toLowerCase`) disagree with Foundation in
 * hundreds of places: a lone combining mark survives Foundation's fold, a
 * halfwidth katakana does not become a fullwidth one, `ﬁ` becomes `fi` but `½`
 * stays `½`. So the table is not written by hand. This compiles
 * `tools/mac-fold.swift` against the real `PaperTextIndex.swift` and
 * `TextNormalization.swift`, asks it, and writes down what it said — the
 * LaTeX table is made the same way (`generate-latex-table.mjs`).
 *
 * The fixture is the other half: strings folded by the real Swift code, which
 * `npm test` holds the port to. Needs macOS and swiftc; re-run whenever either
 * Swift file changes:
 *
 *     node tools/generate-fold-table.mjs
 */
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'

const portable = path.join(import.meta.dirname, '..')
const repo = path.join(portable, '..')
const binary = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'mac-fold-')), 'mac-fold')

execFileSync('swiftc', [
  '-O',
  path.join(repo, 'App/Model/PaperTextIndex.swift'),
  path.join(repo, 'Packages/PaperTimeKit/Sources/PaperCore/Util/TextNormalization.swift'),
  path.join(portable, 'tools/mac-fold.swift'),
  '-o', binary,
], { stdio: 'inherit' })

const ask = (mode, input) => JSON.parse(execFileSync(binary, [mode], {
  input: input === undefined ? undefined : JSON.stringify(input),
  maxBuffer: 1 << 28,
}).toString('utf8'))

// ------------------------------------------------------------------ the table

const table = ask('table')
const hex = (value) => value.toString(16)
/** `cp=a.b.c` pairs, comma separated — twenty kilobytes rather than eighty. */
const pack = (entries) => entries.map(([from, ...to]) => `${hex(from)}=${to.map(hex).join('.')}`).join(',')

// The title fold is the same fold without width, so it is kept as the places
// where it differs: a scalar the full fold changes and the title fold leaves
// alone is written as mapping to itself.
const full = new Map(table.full.map(([from, ...to]) => [from, to]))
const title = new Map(table.title.map(([from, ...to]) => [from, to]))
const titleDelta = []
for (const [from, to] of title) {
  if ((full.get(from) ?? []).join() !== to.join()) titleDelta.push([from, ...to])
}
for (const from of full.keys()) if (!title.has(from)) titleDelta.push([from, from])
titleDelta.sort((a, b) => a[0] - b[0])

const flat = (ranges) => ranges.flat().map(hex).join(',')
const combining = table.combining.map(([from, value]) => `${hex(from)}=${hex(value)}`).join(',')

const source = `/**
 * Foundation's fold, written down.
 *
 * Generated by \`tools/generate-fold-table.mjs\`, which asks the real
 * \`String.folding(options:locale:)\` about every scalar there is. Do not edit
 * by hand; re-run the generator instead.
 *
 * - \`FULL\`: each scalar that \`[.diacriticInsensitive, .caseInsensitive,
 *   .widthInsensitive]\` changes, and what it becomes (\`PaperTextIndex.fold\`).
 * - \`TITLE_DELTA\`: where \`[.diacriticInsensitive, .caseInsensitive]\` — the
 *   fold \`TextNormalization.foldedTitle\` uses — says something else.
 * - \`STRIP_ALL\`: the marks Foundation drops after a letter it decomposes
 *   (Latin, Greek, Cyrillic, and whatever folds into them).
 * - \`STRIP_FEW\`: the marks it drops after any other letter it leaves alone.
 * - \`COMBINING\`: every scalar's canonical combining class that is not 0 —
 *   the order Foundation puts the marks it keeps in.
 */
export const FULL = '${pack(table.full)}'

export const TITLE_DELTA = '${pack(titleDelta)}'

export const STRIP_ALL = '${flat(table.stripAll)}'

export const STRIP_FEW = '${flat(table.stripFew)}'

export const COMBINING = '${combining}'
`
fs.writeFileSync(path.join(portable, 'src/shared/foldTable.ts'), source)
console.log(`foldTable.ts: ${table.full.length} scalars, ${titleDelta.length} title differences, `
  + `${table.stripAll.length} + ${table.stripFew.length} mark ranges`)

// --------------------------------------------------------------- the fixture

/** The same strings every time: a seeded generator, not Math.random. */
function random(seed) {
  let state = seed >>> 0
  return () => {
    state = (state + 0x6D2B79F5) >>> 0
    let t = state
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

